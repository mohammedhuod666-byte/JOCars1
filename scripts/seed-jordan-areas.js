async function main() {
  console.log('--- Ensuring Comprehensive Jordan Areas exist ---');

  for (const [slug, areas] of Object.entries(AREAS_BY_GOV)) {
    const prov = await prisma.province.findFirst({ where: { slug } });
    if (!prov) continue;

    for (const nameAr of areas) {
      const existing = await prisma.city.findFirst({
        where: {
          nameAr: nameAr
        }
      });

      if (!existing) {
        const cleanSlug = nameAr.replace(/[\s\(\)\/]/g, '-') + '-' + slug;
        try {
          await prisma.city.create({
            data: {
              nameAr: nameAr,
              nameEn: nameAr,
              slug: cleanSlug,
              provinceId: prov.id,
              isActive: true
            }
          });
          console.log(`Added [${prov.nameAr}]: ${nameAr}`);
        } catch (e) {
          // ignore unique constraint
        }
      } else {
        // Ensure its provinceId points to this province if not set or mismatched
        if (existing.provinceId !== prov.id) {
          await prisma.$executeRawUnsafe(`UPDATE cities SET "provinceId" = '${prov.id}' WHERE id = '${existing.id}'`);
        }
      }
    }
  }

  console.log('--- Finished Jordan Areas Seeding ---');
}

main().catch(console.error);
