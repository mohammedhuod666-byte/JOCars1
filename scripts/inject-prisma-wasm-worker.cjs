#!/usr/bin/env node
/**
 * Ships Prisma's Query Compiler to the Cloudflare Worker as a pre-compiled module.
 *
 * WHY THIS EXISTS
 * Cloudflare Workers will not compile WebAssembly from bytes. Measured on the real
 * runtime, all three byte paths fail the same way:
 *
 *   new WebAssembly.Module(bytes)   -> CompileError: Wasm code generation
 *   WebAssembly.compile(bytes)      ->   disallowed by embedder
 *   WebAssembly.instantiate(bytes)  ->   (same)
 *
 * A statically imported module does work — wrangler uploads it as a
 * `CompiledWasm` module and the runtime compiles it at deploy time. So the fix is
 * to make the Worker's entry module import the compiler, exactly as that probe did.
 *
 * WHY A POST-BUILD STEP RATHER THAN BUNDLER CONFIG
 * OpenNext flattens the whole server into `.open-next/worker.js` (a 2 KB entry that
 * imports the real chunks). Prisma's `require('./query_compiler_bg.wasm')` sits
 * inside that flattened graph where esbuild has already decided, and esbuild has no
 * `CompiledWasm` output mode — its choices are `binary` (inline as base64, which the
 * runtime then refuses to compile) and `file` (emit a path, which does not exist at
 * runtime). Injecting into the generated entry is therefore the only place where a
 * genuine static import can still be created, and it is also the smallest possible
 * change: three added lines in a file that is regenerated on every build.
 *
 * WHAT IT DOES
 *   1. copies `query_compiler_bg.wasm` to `.open-next/prisma-query-compiler.wasm`
 *   2. prepends a static import of it to `.open-next/worker.js`
 *   3. sets `globalThis.__JO_CARS_PRISMA_WASM__` to the module
 *
 * Step 3 is what `scripts/patch-prisma-wasm-inline.cjs` looks for first; the
 * inlined base64 it also installed remains the path used by Node (Vercel, local
 * development), so one generated client serves both platforms.
 *
 * Idempotent, and fails loudly rather than leaving a Worker that 500s on queries.
 */

const fs = require('fs');
const path = require('path');

const OPEN_NEXT = '.open-next';
const ENTRY = path.join(OPEN_NEXT, 'worker.js');
const WASM_SRC = path.join('node_modules', '.prisma', 'client', 'query_compiler_bg.wasm');
const WASM_NAME = 'prisma-query-compiler.wasm';
const WASM_DEST = path.join(OPEN_NEXT, WASM_NAME);

const MARKER = 'jo-cars: prisma query compiler module';

if (!fs.existsSync(ENTRY)) {
  console.error(
    `[inject-prisma-wasm] ${ENTRY} not found. Run \`opennextjs-cloudflare build\` first — ` +
      'this step must run after it, because OpenNext regenerates the entry module.',
  );
  process.exit(1);
}

if (!fs.existsSync(WASM_SRC)) {
  console.error(
    `[inject-prisma-wasm] ${WASM_SRC} not found. Run \`prisma generate\` first.`,
  );
  process.exit(1);
}

let entry = fs.readFileSync(ENTRY, 'utf8');

if (entry.includes(MARKER)) {
  // Re-copy the compiler anyway: a fresh `prisma generate` produces new bytes, and
  // a stale copy would silently run the old query compiler.
  fs.copyFileSync(WASM_SRC, WASM_DEST);
  console.log('[inject-prisma-wasm] already injected; compiler refreshed.');
  process.exit(0);
}

// 1. Place the compiler next to the entry so a relative import resolves, the same
//    way wrangler resolved ./cloudflare/images.js and ./middleware/handler.mjs.
fs.copyFileSync(WASM_SRC, WASM_DEST);

// 2. Prepend the static import and the global that the Prisma loader reads.
const preamble = `// ${MARKER}
// Cloudflare Workers refuse to compile WebAssembly from bytes, so the Query
// Compiler is uploaded as a pre-compiled module and bound here for the Prisma
// client loader to find. Generated by scripts/inject-prisma-wasm-worker.cjs — do
// not edit; this file is regenerated by every OpenNext build.
import __prismaQueryCompiler from "./${WASM_NAME}";
globalThis.__JO_CARS_PRISMA_WASM__ = __prismaQueryCompiler;

`;

fs.writeFileSync(ENTRY, preamble + entry, 'utf8');

const kb = (fs.statSync(WASM_DEST).size / 1024).toFixed(0);
console.log(
  `[inject-prisma-wasm] injected static import of ./${WASM_NAME} (${kb} KB) into ${ENTRY}.`,
);

// 3. Confirm the import survived, rather than reporting success optimistically.
const after = fs.readFileSync(ENTRY, 'utf8');
if (!after.includes(`from "./${WASM_NAME}"`)) {
  console.error('[inject-prisma-wasm] verification failed: import statement not present after write.');
  process.exit(1);
}
if (!fs.existsSync(WASM_DEST)) {
  console.error('[inject-prisma-wasm] verification failed: compiler file missing.');
  process.exit(1);
}
console.log('[inject-prisma-wasm] verified.');