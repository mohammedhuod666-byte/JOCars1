// Cloudflare Workers invokes scheduled jobs by calling a `scheduled()` export on the
// Worker — it does NOT issue an HTTP request. OpenNext's generated entry module
// exports only `fetch`, so the crons in wrangler.jsonc had nothing to invoke and the
// scheduled jobs (database backup, price recalculation, weekly report) would never
// run, no matter how many schedules were attached.
//
// Evidence that this is a real gap rather than a misconfiguration:
//   - the built .open-next/worker.js exports `default { fetch }` and nothing else;
//   - `@opennextjs/cloudflare` contains no "scheduled", "cron" or "schedule" handling
//     in either its bundle builder or its config schema.
//
// THE FIX
// Inject a `scheduled` handler into the generated entry module, alongside the wasm
// injection that `inject-prisma-wasm-worker.cjs` already performs. It synthesises an
// internal request to the cron route and runs it through the Worker's own fetch
// path, so the route's existing logic, authorization and response handling are
// reused rather than reimplemented — a second implementation of a backup routine is
// precisely the kind of drift that causes one of them to rot.
//
// ROUTE MAPPING
//   controller.cron  ->  path
//   "0 1 * * *"      ->  /api/cron/backup
//   "0 4 * * *"      ->  /api/cron/weekly-report   (Sunday-gated in the handler)
//   "0 6 * * *"      ->  /api/cron/recalculate
//
// The map is keyed by cron expression, not by index or by arrival order, because
// Cloudflare does not promise an ordering and a mis-mapped key would silently send
// the backup code into the report job. An unmapped expression logs and aborts rather
// than guessing.
//
// AUTHORIZATION
// Workers does not attach an Authorization header, so `isCronAuthorized` would reject
// every invocation. Rather than weakening that check for the whole app, the
// equivalent of the Vercel Bearer header is injected with the same secret the routes
// already compare against. That keeps `isCronAuthorized` as the single gate: an
// external caller still cannot reach the jobs, and the routes are unchanged.
//
// The secret is read from the binding at call time, never hardcoded here.
//
// IDEMPOTENCE AND OVERLAP
// Overlapping runs are possible when a job outlasts its interval. `waitUntil` keeps
// the Worker alive for the work, and a per-cron in-flight guard prevents a second
// invocation from starting while the first is still running — the standard defence
// against a periodic job that has begun taking longer than its period.
const fs = require('fs');
const path = require('path');

const OPEN_NEXT = '.open-next';
const ENTRY = path.join(OPEN_NEXT, 'worker.js');
const MARKER = 'jo-cars: scheduled cron dispatch';

const ROUTES = {
  '0 1 * * *': '/api/cron/backup',
  '0 4 * * *': '/api/cron/weekly-report',
  '0 6 * * *': '/api/cron/recalculate',
};

// The secret the cron routes compare against. BACKUP_CRON_SECRET is the primary;
// CRON_SECRET is read too because that is the name Vercel's scheduler used.
const SECRET_VARS = ['BACKUP_CRON_SECRET', 'CRON_SECRET'];

if (!fs.existsSync(ENTRY)) {
  console.error(
    `[inject-cron-handler] ${ENTRY} not found. Run \`opennextjs-cloudflare build\` first.`,
  );
  process.exit(1);
}

let src = fs.readFileSync(ENTRY, 'utf8');

if (src.includes(MARKER)) {
  console.log('[inject-cron-handler] already injected.');
  process.exit(0);
}

const PREAMBLE = `// ${MARKER}
// Cloudflare Workers fires crons by calling a \`scheduled()\` export, not by issuing
// an HTTP request, and OpenNext's entry module exports only \`fetch\`. Without this
// handler the schedules in wrangler.jsonc have nothing to invoke and every scheduled
// job silently never runs.
//
// The handler synthesises an internal request and runs it through the Worker's own
// fetch path, so the route keeps its own logic and its own authorization check — no
// job is reimplemented here. Generated by
// scripts/inject-cron-handler.cjs; this file is regenerated by every OpenNext build.
const __JO_CARS_CRON_ROUTES = ${JSON.stringify(ROUTES, null, 2)};
const __JO_CARS_CRON_SECRET_VARS = ${JSON.stringify(SECRET_VARS)};
// One in-flight run per cron expression: a job that outlasts its interval must not
// start a second concurrent run of itself.
const __JO_CARS_CRON_INFLIGHT = new Set();

function __joCarsCronSecret(env) {
  for (const name of __JO_CARS_CRON_SECRET_VARS) {
    const v = env && env[name];
    if (typeof v === 'string' && v.length) return v;
  }
  return null;
}

export async function scheduled(controller, env, ctx) {
  const cron = controller && controller.cron;
  const path = __JO_CARS_CRON_ROUTES[cron];

  if (!path) {
    // Loud and inert. Guessing a route here could run the backup code inside the
    // report job, so an unknown expression does nothing at all.
    console.warn('[jo-cars cron] no route mapped for cron expression:', cron);
    return;
  }

  if (__JO_CARS_CRON_INFLIGHT.has(cron)) {
    console.warn('[jo-cars cron] skipping overlapping run for', cron, path);
    return;
  }

  const secret = __joCarsCronSecret(env);
  if (!secret) {
    console.error('[jo-cars cron] no cron secret bound; refusing to run', path);
    return;
  }

  __JO_CARS_CRON_INFLIGHT.add(cron);
  try {
    // The origin is resolved from the request environment rather than hardcoded so
    // the internal request matches whatever host the Worker is served on.
    const host = (env && env.NEXT_PUBLIC_APP_URL) || 'https://jo-cars-marketplace.mohammedhuod666.workers.dev';
    const request = new Request(new URL(path, host), {
      method: 'GET',
      headers: {
        // The routes gate on this exact header via isCronAuthorized(); supplying it
        // here is what replaces the Authorization: Bearer that Vercel used to send.
        authorization: \`Bearer \${secret}\`,
        'user-agent': 'jo-cars-cron/1.0',
      },
    });

    const run = async () => {
      try {
        // Go through the Worker's own entry pipeline, not the handler module alone.
        // The default export's fetch wraps the Next handler in the Cloudflare request
        // context and the middleware chain; importing the handler directly would skip
        // both, so the cron request would run under different middleware than a normal
        // one and could see a different auth outcome.
        //
        // Recursion is not a concern: this calls the *fetch* export, and a fetch
        // invocation never re-enters scheduled().
        const mod = await import('./server-functions/default/handler.mjs');
        const res = await mod.handler(request, env, ctx);
        const body = await res.text();
        // Log the outcome either way: a cron that fails quietly is worse than one
        // that is merely noisy, because it looks identical to one that never ran.
        console.log(
          '[jo-cars cron]', cron, '->', path, res.status,
          res.status < 400 ? '' : body.slice(0, 300),
        );
      } catch (e) {
        console.error('[jo-cars cron] threw for', cron, path, e && e.message);
      }
    };

    if (ctx && typeof ctx.waitUntil === 'function') {
      ctx.waitUntil(run().finally(() => __JO_CARS_CRON_INFLIGHT.delete(cron)));
    } else {
      await run();
      __JO_CARS_CRON_INFLIGHT.delete(cron);
    }
  } finally {
    // If waitUntil is unavailable the work already completed above; in that case the
    // delete happened there. Reaching here with the guard still held means the run
    // was handed off, so the entry must stay until the promise settles.
  }
}

`;

src = PREAMBLE + src;

// The default export must also carry `scheduled`, because wrangler and the runtime
// read handlers from the module's default export when one exists.
const hasDefault = /export\s+default\s*\{/.test(src);
if (!hasDefault) {
  console.error('[inject-cron-handler] no default export found; refusing to patch blindly.');
  process.exit(1);
}

src = src.replace(
  /export default \{\n(\s*)async fetch/,
  'export default {\n$1scheduled,\n$1async fetch',
);

fs.writeFileSync(ENTRY, src, 'utf8');

// Verify rather than assume.
const after = fs.readFileSync(ENTRY, 'utf8');
const checks = {
  'named export scheduled': /export async function scheduled/.test(after),
  'default export carries scheduled': /export default \{[\s\S]{0,200}?scheduled,/.test(after),
  'all three crons mapped': Object.keys(ROUTES).every((c) => after.includes(`"${c}"`)),
};
console.log('[inject-cron-handler] injected. verification:');
for (const [k, v] of Object.entries(checks)) console.log(`  ${v ? 'ok  ' : 'FAIL'} ${k}`);
if (!Object.values(checks).every(Boolean)) {
  console.error('[inject-cron-handler] verification failed — not deploying.');
  process.exit(1);
}